export const LANGUAGES = Object.keys(STRINGS);
let current = "de";

export function setLang(lang) {
  current = LANGUAGES.includes(lang) ? lang : "de";
  document.documentElement.lang = current;
}
export function getLang() {
  return current;
}

/** Text for a key; vars replaces {placeholders}. Falls back to German, then to the key itself. */
export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.de[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return s;
}

/** Number formatted for the current language, at most 2 decimals. */
export function fmt(n) {
  return (+n).toLocaleString(current === "de" ? "de-DE" : "en-US", { maximumFractionDigits: 2 });
}

/** Fills every element with data-i18n inside root. */
export function applyStaticTexts(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
}
